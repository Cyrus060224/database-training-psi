#!/bin/bash

# ===================================================================
# 商品购销存管理系统 (PSI System) - 一键停止服务脚本
# ===================================================================

echo "🛑 正在停止商品购销存管理系统服务..."

# 1. 关闭后端 (端口 5050)
PID_5050=$(lsof -ti:5050 2>/dev/null)
if [ -n "$PID_5050" ]; then
    kill -9 $PID_5050
    echo "✅ 后端 Web API 服务已停止 (Port 5050)"
else
    echo "ℹ️ 后端未在运行"
fi

# 2. 关闭前端 (端口 5173)
PID_5173=$(lsof -ti:5173 2>/dev/null)
if [ -n "$PID_5173" ]; then
    kill -9 $PID_5173
    echo "✅ 前端 Vite 服务已停止 (Port 5173)"
else
    echo "ℹ️ 前端未在运行"
fi

echo "🎉 进程已全部释放！"
